// PreToolUse hook: refuse edits that are known to destroy work.
//
// Two classes of path, both documented in CLAUDE.md but until now
// enforced only by prose (or by CI, long after the edit):
//
//   1. `docs/CATALOG_*.md` — "Editing them via `Write` is unsafe —
//      always use `Edit` for additions, reserve `Write` for new files."
//      CATALOG_BACKEND_PLAN.md alone is ~3k lines; a whole-file Write
//      silently truncates it. `Edit` stays allowed, which is the point.
//
//   2. Generated artifacts — hand edits are erased by the next codegen
//      run (tokens.css, messages*.ts) or fail a CI drift check
//      (privacy.html, setup.html, schema/v1/*.json). Both tool calls
//      are refused: there is no correct way to hand-edit these, only a
//      source file to edit instead.
//
// Plus lock files, which should only move via their package manager.
//
// Deliberately NOT guarded: `locales/*.json`. CLAUDE.md permits
// one-off hand fixes there ("the canonical surface is Weblate" is
// about where translations *come from*, not a prohibition), so a deny
// would contradict documented policy.
//
// Fails OPEN. A guard that crashes must never brick a session, so any
// unexpected input or internal error allows the call through.

import { relative, isAbsolute } from 'node:path'

/** @type {{ test: (p: string) => boolean, tools: string[], reason: string }[]} */
const RULES = [
  {
    tools: ['Write'],
    test: (p) => /^docs\/CATALOG_[^/]*\.md$/.test(p),
    reason:
      'CLAUDE.md: the CATALOG_* plan docs are edited with Edit, never Write — ' +
      'a whole-file Write truncates a multi-thousand-line document. ' +
      'Use Edit to add a section (and commit each section before starting the next).',
  },
  {
    tools: ['Write', 'Edit'],
    test: (p) => p === 'src/styles/tokens.css',
    reason:
      'Generated from tokens/*.json by `npm run tokens` (and postinstall/build), and gitignored. ' +
      'Edit the source under tokens/ instead.',
  },
  {
    tools: ['Write', 'Edit'],
    test: (p) => /^src\/i18n\/messages(\.[^/]+)?\.ts$/.test(p),
    reason:
      'Generated from locales/en.json by `npm run locales`, and gitignored. ' +
      'Add the key to locales/en.json instead, then re-run the codegen.',
  },
  {
    tools: ['Write', 'Edit'],
    test: (p) => p === 'public/privacy.html',
    reason:
      'Generated from docs/PRIVACY.md by `npm run build:privacy-page`; ' +
      '`npm run check:privacy-page` fails CI on drift. Edit docs/PRIVACY.md instead.',
  },
  {
    tools: ['Write', 'Edit'],
    test: (p) => p === 'public/setup.html',
    reason:
      'Generated by `npm run build:setup-page`; `npm run check:setup-page` fails CI on drift. ' +
      'Edit the generator under scripts/ instead.',
  },
  {
    tools: ['Write', 'Edit'],
    test: (p) => /^public\/schema\/v1\/[^/]+\.json$/.test(p),
    reason:
      'Generated by `npm run gen:protocol-schemas` from the TS types; ' +
      '`npm run check:protocol-schemas` fails CI on drift. Edit the source types instead.',
  },
  {
    tools: ['Write', 'Edit'],
    test: (p) => /(^|\/)(package-lock\.json|Cargo\.lock)$/.test(p),
    reason: 'Lock files should only change via their package manager (npm / cargo), not by hand.',
  },
]

function deny(reason) {
  process.stdout.write(
    JSON.stringify({
      hookSpecificOutput: {
        hookEventName: 'PreToolUse',
        permissionDecision: 'deny',
        permissionDecisionReason: reason,
      },
    })
  )
  process.exit(0)
}

async function main() {
  let raw = ''
  for await (const chunk of process.stdin) raw += chunk

  const payload = JSON.parse(raw)
  const tool = payload.tool_name
  const filePath = payload?.tool_input?.file_path
  if (!tool || typeof filePath !== 'string') return

  // Normalize to repo-relative, posix separators. A path outside the
  // project (absolute, elsewhere) relativizes to something starting
  // with '..' and matches no rule — which is the correct outcome.
  const root = process.env.CLAUDE_PROJECT_DIR || payload.cwd || process.cwd()
  const rel = (isAbsolute(filePath) ? relative(root, filePath) : filePath).split('\\').join('/')

  for (const rule of RULES) {
    if (rule.tools.includes(tool) && rule.test(rel)) {
      deny(`Refused edit to ${rel}. ${rule.reason}`)
    }
  }
}

main().catch(() => {
  // Fail open — never block on an internal error.
  process.exit(0)
})
